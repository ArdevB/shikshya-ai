"""
Trains the at-risk model and writes the model, its metrics and a model card.

Run from apps/ai: python -m ml.train

Compares Logistic Regression and Random Forest with stratified 5-fold cross-validation. Missing a
student who then fails costs far more than a teacher checking on one who was fine, so recall on the
at-risk class comes first: the winner is the better F2 score, which counts recall twice as heavily
as precision, and the alert threshold is then set to reach the target recall.
"""

import json
from datetime import UTC, datetime
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.base import clone
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    f1_score,
    fbeta_score,
    precision_recall_curve,
    precision_score,
    recall_score,
    roc_auc_score,
)
from sklearn.model_selection import StratifiedKFold, cross_val_predict, train_test_split
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler

from ml.features import FEATURE_NAMES, FEATURES
from ml.generate_synthetic import generate

SEED = 42
TARGET_RECALL = 0.82

HERE = Path(__file__).parent
MODEL_PATH = HERE / "risk_model.joblib"
METRICS_PATH = HERE / "metrics.json"
CARD_PATH = HERE / "model_card.md"


def candidates() -> dict[str, Pipeline]:
    return {
        "Logistic Regression": Pipeline(
            [
                ("impute", SimpleImputer(strategy="median")),
                ("scale", StandardScaler()),
                ("model", LogisticRegression(max_iter=1000, class_weight="balanced")),
            ]
        ),
        "Random Forest": Pipeline(
            [
                ("impute", SimpleImputer(strategy="median")),
                (
                    "model",
                    RandomForestClassifier(
                        n_estimators=150,
                        max_depth=8,
                        min_samples_leaf=5,
                        class_weight="balanced",
                        random_state=SEED,
                        n_jobs=-1,
                    ),
                ),
            ]
        ),
    }


def scores(y_true: np.ndarray, probability: np.ndarray, threshold: float) -> dict[str, float]:
    predicted = (probability >= threshold).astype(int)
    return {
        "accuracy": round(float(accuracy_score(y_true, predicted)), 4),
        "precision": round(float(precision_score(y_true, predicted, zero_division=0)), 4),
        "recall": round(float(recall_score(y_true, predicted)), 4),
        "f1": round(float(f1_score(y_true, predicted)), 4),
        "f2": round(float(fbeta_score(y_true, predicted, beta=2)), 4),
        "roc_auc": round(float(roc_auc_score(y_true, probability)), 4),
    }


def threshold_for_recall(y_true: np.ndarray, probability: np.ndarray, target: float) -> float:
    """The highest threshold that still reaches the target recall, keeping alerts to a minimum."""
    _, recall, thresholds = precision_recall_curve(y_true, probability)
    # recall has one more entry than thresholds, and falls as the threshold rises.
    reaching = np.where(recall[:-1] >= target)[0]
    return round(float(thresholds[reaching[-1]]), 4) if len(reaching) else 0.5


def importances(pipeline: Pipeline) -> np.ndarray:
    """How much each feature matters overall, summing to 1, whichever model won."""
    model = pipeline.named_steps["model"]
    raw = np.abs(model.coef_[0]) if hasattr(model, "coef_") else model.feature_importances_
    return raw / raw.sum()


def write_card(metrics: dict, importance: dict[str, float]) -> None:
    test = metrics["test"]
    rows = "\n".join(
        f"| {name} | {values['accuracy']} | {values['precision']} | {values['recall']} "
        f"| {values['f1']} | {values['f2']} | {values['roc_auc']} |"
        for name, values in metrics["cross_validation"].items()
    )
    features = "\n".join(
        f"| `{feature.name}` | {feature.label} | "
        f"{'higher means more risk' if feature.risk_direction > 0 else 'lower means more risk'} | "
        f"{importance[feature.name]:.1%} |"
        for feature in FEATURES
    )
    CARD_PATH.write_text(
        f"""# Model card: at-risk student prediction

Generated by `python -m ml.train` on {metrics["trained_at"][:10]}. Do not edit by hand.

## What it does

Estimates the chance that a student will fail a course, from how they are doing in it so far. The
result goes to teachers as a prompt to check on someone. It is never shown to the student, and it
does not decide anything by itself.

## Data

**The model is trained on synthetic data**, because Shikshya has no real history yet.
`ml/generate_synthetic.py` lists its assumptions, and it made {metrics["rows"]} rows, of which
{metrics["at_risk_share"]:.1%} are at risk. These figures therefore show that the method works on
data with that shape. They do not show how accurate it would be for a real college, so retrain on
real past results before relying on it.

## Features

| Feature | Meaning | Direction | Share of importance |
| --- | --- | --- | --- |
{features}

Missing values are filled with the median from training: new students have no previous GPA, and
early in a semester there may be no exam marks.

## Choosing the model

5-fold stratified cross-validation on the training split, at a threshold of 0.5:

| Model | Accuracy | Precision | Recall | F1 | F2 | ROC-AUC |
| --- | --- | --- | --- | --- | --- | --- |
{rows}

**Chosen: {metrics["model"]}**, for the better F2 score. F2 counts recall twice as heavily as
precision, because missing a student who then fails is worse than a teacher checking on one who
was fine.

## Results on the held-out test split

A student is flagged at a probability of {metrics["alert_threshold"]} or more, a threshold set on
the training split to reach {TARGET_RECALL:.0%} recall.

| Accuracy | Precision | Recall | F1 | ROC-AUC |
| --- | --- | --- | --- | --- |
| {test["accuracy"]} | {test["precision"]} | {test["recall"]} | {test["f1"]} | {test["roc_auc"]} |

Levels: below {metrics["alert_threshold"]} is LOW, from there to below
{metrics["high_risk_threshold"]} is MEDIUM, and {metrics["high_risk_threshold"]} or more is HIGH.

## Reasons shown to teachers

Each feature's contribution is its importance, multiplied by how far the student is from the
typical value, in standard deviations, in the risky direction. The largest positive contributions
become the reasons. This is an approximation that is simple to explain, not a causal claim.

## Limitations

- Trained on made-up data, so the real-world accuracy is unknown.
- About {1 - test["precision"]:.0%} of the students it flags on this data would pass anyway, and it
  still misses about {1 - test["recall"]:.0%} of those who fail. It is a prompt, not a verdict.
- It only sees numbers. Illness, family events and the like are invisible to it.
- It has not been checked for fairness between groups of students, and the data has no such groups.
""",
        encoding="utf-8",
    )


def main() -> dict:
    frame = generate()
    x = frame[list(FEATURE_NAMES)]
    y = frame["at_risk"].to_numpy()
    x_train, x_test, y_train, y_test = train_test_split(
        x, y, test_size=0.2, stratify=y, random_state=SEED
    )

    folds = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)
    cross_validation: dict[str, dict[str, float]] = {}
    out_of_fold: dict[str, np.ndarray] = {}
    for name, pipeline in candidates().items():
        out_of_fold[name] = cross_val_predict(
            pipeline, x_train, y_train, cv=folds, method="predict_proba"
        )[:, 1]
        cross_validation[name] = scores(y_train, out_of_fold[name], 0.5)

    best = max(cross_validation, key=lambda name: cross_validation[name]["f2"])
    # Out-of-fold predictions, so the threshold is not tuned on data the model has memorised.
    alert_threshold = threshold_for_recall(y_train, out_of_fold[best], TARGET_RECALL)

    # Halfway from the alert threshold to certainty, so both of the upper levels mean something.
    high_risk_threshold = round((alert_threshold + 1) / 2, 4)

    pipeline = clone(candidates()[best]).fit(x_train, y_train)
    test = scores(y_test, pipeline.predict_proba(x_test)[:, 1], alert_threshold)

    importance = dict(zip(FEATURE_NAMES, importances(pipeline).round(4).tolist(), strict=True))
    artifact = {
        "pipeline": pipeline,
        "feature_names": list(FEATURE_NAMES),
        "alert_threshold": alert_threshold,
        "high_risk_threshold": high_risk_threshold,
        "importance": importance,
        "median": x_train.median().to_dict(),
        "std": x_train.std().to_dict(),
    }
    joblib.dump(artifact, MODEL_PATH, compress=3)

    metrics = {
        "trained_at": datetime.now(UTC).isoformat(),
        "rows": len(frame),
        "at_risk_share": float(np.mean(y)),
        "model": best,
        "cross_validation": cross_validation,
        "alert_threshold": alert_threshold,
        "high_risk_threshold": high_risk_threshold,
        "target_recall": TARGET_RECALL,
        "test": test,
    }
    METRICS_PATH.write_text(json.dumps(metrics, indent=2) + "\n", encoding="utf-8")
    write_card(metrics, importance)

    print(pd.DataFrame(cross_validation).T.to_string())
    print(f"\nChosen: {best}, alert threshold {alert_threshold}")
    print(f"Test: {test}")
    return metrics


if __name__ == "__main__":
    main()
