import { formatNpr, type InvoiceView, type PaymentView } from '@shikshya/shared';
import { dateText, documentPage, esc, factList, momentText, type Institution } from './layout.js';

const METHOD_LABEL: Record<PaymentView['method'], string> = {
  ESEWA: 'eSewa',
  KHALTI: 'Khalti',
  CASH: 'Cash',
  BANK: 'Bank deposit',
};

export function invoiceHtml(institution: Institution, invoice: InvoiceView) {
  const rows = invoice.items
    .map(
      (item) =>
        `<tr><td>${esc(item.description)}</td><td class="num">${esc(formatNpr(item.amountPaisa))}</td></tr>`,
    )
    .join('');

  const totals: [string, number][] = [['Total', invoice.totalPaisa]];
  if (invoice.finePaisa > 0) totals.push(['Late fine', invoice.finePaisa]);
  if (invoice.discountPaisa > 0) totals.push(['Discount', -invoice.discountPaisa]);
  if (invoice.paidPaisa > 0) totals.push(['Paid', -invoice.paidPaisa]);
  const totalRows = totals
    .map(
      ([label, paisa]) =>
        `<tr><td>${esc(label)}</td><td class="num">${paisa < 0 ? '- ' : ''}${esc(formatNpr(Math.abs(paisa)))}</td></tr>`,
    )
    .join('');

  return documentPage(
    institution,
    `Invoice ${invoice.invoiceNumber}`,
    `<div class="doc-title"><h2>Invoice</h2><span class="accent">${esc(invoice.status)}</span></div>
    ${factList([
      ['Invoice no.', invoice.invoiceNumber],
      ['Issue date', dateText(invoice.issueDate)],
      ['Student', invoice.studentName],
      ['Due date', dateText(invoice.dueDate)],
      ['Roll no.', invoice.rollNumber],
      ['Program', `${invoice.programCode}, Semester ${invoice.semesterNumber}`],
    ])}
    <table><thead><tr><th>Description</th><th class="num">Amount</th></tr></thead><tbody>${rows}</tbody></table>
    <table class="totals">${totalRows}
      <tr class="grand"><td>Outstanding</td><td class="num">${esc(formatNpr(invoice.outstandingPaisa))}</td></tr>
    </table>
    <div class="footer">Please pay by the due date. A late fine may apply afterwards.</div>`,
  );
}

export function receiptHtml(institution: Institution, payment: PaymentView, invoice: InvoiceView) {
  return documentPage(
    institution,
    `Receipt ${payment.receiptNumber ?? ''}`,
    `<div class="doc-title"><h2>Payment receipt</h2><span class="accent">PAID</span></div>
    ${factList([
      ['Receipt no.', payment.receiptNumber ?? ''],
      ['Date', payment.paidAt ? momentText(payment.paidAt) : ''],
      ['Student', invoice.studentName],
      ['Roll no.', invoice.rollNumber],
      ['Invoice no.', invoice.invoiceNumber],
      ['Program', `${invoice.programCode}, Semester ${invoice.semesterNumber}`],
      ['Payment method', METHOD_LABEL[payment.method]],
      ['Reference', payment.gatewayRef || '-'],
    ])}
    <table class="totals">
      <tr class="grand"><td>Amount received</td><td class="num">${esc(formatNpr(payment.amountPaisa))}</td></tr>
      <tr><td>Still outstanding</td><td class="num">${esc(formatNpr(invoice.outstandingPaisa))}</td></tr>
    </table>
    <div class="signature"><div>Accounts office</div></div>
    <div class="footer">This receipt was generated by Shikshya.</div>`,
  );
}
